/**
 * 为 perf:window 准备千万行工作表 + 根目录 .perf-env.json。
 *
 * 行数据用 Postgres generate_series + gen_random_uuid() 直写，
 * 避免经 HTTP 逐条插入（10M 行会极慢）。
 *
 * Usage: node scripts/perf/seed-10m-sheet.mjs
 * Env:
 *   PERF_API=http://127.0.0.1:3000
 *   PERF_ROWS=10000000
 *   PERF_PG_CONTAINER=smart-table-postgres
 *   PERF_PG_USER / PERF_PG_DB（默认 smarttable）
 */
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';

const API = process.env.PERF_API ?? 'http://127.0.0.1:3000';
const ROWS = Math.max(1_000, Number(process.env.PERF_ROWS ?? 10_000_000));
const PG_CONTAINER = process.env.PERF_PG_CONTAINER ?? 'smart-table-postgres';
const PG_USER = process.env.PERF_PG_USER ?? 'smarttable';
const PG_DB = process.env.PERF_PG_DB ?? 'smarttable';
const BATCH = Math.max(50_000, Number(process.env.PERF_INSERT_BATCH ?? 500_000));

const password = 'Ab12_cd34';
const account = `perf10m${String(Date.now()).slice(-8)}`;

async function api(path, { method = 'GET', token, body } = {}) {
  const response = await fetch(`${API}${path}`, {
    method,
    headers: {
      'Content-Type': 'application/json',
      ...(token ? { Authorization: `Bearer ${token}` } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await response.text();
  let data;
  try {
    data = text ? JSON.parse(text) : null;
  } catch {
    data = text;
  }
  if (!response.ok) {
    throw new Error(`${method} ${path} → ${response.status}: ${text.slice(0, 400)}`);
  }
  return data;
}

function psql(sql) {
  execFileSync(
    'docker',
    ['exec', '-i', PG_CONTAINER, 'psql', '-U', PG_USER, '-d', PG_DB, '-v', 'ON_ERROR_STOP=1', '-c', sql],
    { stdio: ['ignore', 'inherit', 'inherit'] },
  );
}

function psqlScalar(sql) {
  const out = execFileSync(
    'docker',
    [
      'exec',
      '-i',
      PG_CONTAINER,
      'psql',
      '-U',
      PG_USER,
      '-d',
      PG_DB,
      '-t',
      '-A',
      '-c',
      sql,
    ],
    { encoding: 'utf8' },
  );
  return out.trim();
}

console.log(`register ${account} …`);
const owner = await api('/auth/register', {
  method: 'POST',
  body: {
    account,
    password,
    securityQuestion: '你小学就读的学校名称是？',
    securityAnswer: 'demo',
  },
});
const token = owner.accessToken;
const workspace = await api('/workspaces', {
  method: 'POST',
  token,
  body: { name: `perf-10m-${Date.now()}` },
});
const base = await api(`/workspaces/${workspace.id}/bases`, {
  method: 'POST',
  token,
  body: { name: '10M Window' },
});
const sheet = await api(`/bases/${base.id}/sheets`, {
  method: 'POST',
  token,
  body: { name: 'window-10m', seed: false },
});

console.log(`sheet=${sheet.id}; wiping seed rows then inserting ${ROWS} …`);
psql(`DELETE FROM records WHERE sheet_id = '${sheet.id}'::uuid;`);

const started = Date.now();
let done = 0;
while (done < ROWS) {
  const n = Math.min(BATCH, ROWS - done);
  // gen_random_uuid：与 window-fetch 的 randomUUID cursor 同属 v4 空间，利于深翻页采样
  psql(`
    INSERT INTO records (id, sheet_id, cells, version, created_at, updated_at)
    SELECT gen_random_uuid(), '${sheet.id}'::uuid, '{}'::jsonb, 1, NOW(), NOW()
    FROM generate_series(1, ${n});
  `);
  done += n;
  const elapsed = ((Date.now() - started) / 1000).toFixed(1);
  console.log(`  ${done}/${ROWS} (${elapsed}s)`);
}

const count = Number(
  psqlScalar(`SELECT COUNT(*) FROM records WHERE sheet_id = '${sheet.id}'::uuid;`),
);
if (count < ROWS) {
  throw new Error(`expected ≥${ROWS} rows, got ${count}`);
}

const env = {
  token,
  sheetId: sheet.id,
  workspaceId: workspace.id,
  baseId: base.id,
  account,
  rows: count,
  createdAt: new Date().toISOString(),
  note: 'generated by scripts/perf/seed-10m-sheet.mjs',
  probeCursor: randomUUID(),
};
await writeFile('.perf-env.json', `${JSON.stringify(env, null, 2)}\n`, 'utf8');
console.log(
  JSON.stringify(
    {
      ok: true,
      rows: count,
      sheetId: sheet.id,
      elapsedSec: Number(((Date.now() - started) / 1000).toFixed(1)),
      envFile: '.perf-env.json',
    },
    null,
    2,
  ),
);
